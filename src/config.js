import convict from 'convict'
import convictFormatWithValidator from 'convict-format-with-validator'

import { convictValidateMongoUri } from '#/common/helpers/convict/validate-mongo-uri.js'

convict.addFormat(convictValidateMongoUri)
convict.addFormats(convictFormatWithValidator)

const isProduction = process.env.NODE_ENV === 'production'
const isTest = process.env.NODE_ENV === 'test'

export const config = convict({
  serviceVersion: {
    doc: 'The service version, this variable is injected into your docker container in CDP environments',
    format: String,
    nullable: true,
    default: null,
    env: 'SERVICE_VERSION'
  },
  host: {
    doc: 'The IP address to bind',
    format: 'ipaddress',
    default: '0.0.0.0',
    env: 'HOST'
  },
  port: {
    doc: 'The port to bind',
    format: 'port',
    default: 3001,
    env: 'PORT'
  },
  serviceName: {
    doc: 'Api Service Name',
    format: String,
    default: 'aqie-prtr-submissions-backend'
  },
  cdpEnvironment: {
    doc: 'The CDP environment the app is running in. With the addition of "local" for local development',
    format: [
      'local',
      'infra-dev',
      'management',
      'dev',
      'test',
      'perf-test',
      'ext-test',
      'prod'
    ],
    default: 'local',
    env: 'ENVIRONMENT'
  },
  log: {
    isEnabled: {
      doc: 'Is logging enabled',
      format: Boolean,
      default: !isTest,
      env: 'LOG_ENABLED'
    },
    level: {
      doc: 'Logging level',
      format: ['fatal', 'error', 'warn', 'info', 'debug', 'trace', 'silent'],
      default: 'info',
      env: 'LOG_LEVEL'
    },
    format: {
      doc: 'Format to output logs in',
      format: ['ecs', 'pino-pretty'],
      default: isProduction ? 'ecs' : 'pino-pretty',
      env: 'LOG_FORMAT'
    },
    redact: {
      doc: 'Log paths to redact',
      format: Array,
      default: isProduction
        ? ['req.headers.authorization', 'req.headers.cookie', 'res.headers']
        : ['req', 'res', 'responseTime']
    }
  },
  mongo: {
    mongoUrl: {
      doc: 'URI for mongodb',
      format: String,
      default: 'mongodb://127.0.0.1:27017/',
      env: 'MONGO_URI'
    },
    databaseName: {
      doc: 'database for mongodb',
      format: String,
      default: 'aqie-prtr-submissions-backend',
      env: 'MONGO_DATABASE'
    },
    mongoOptions: {
      retryWrites: {
        doc: 'Enable Mongo write retries, overrides mongo URI when set.',
        format: Boolean,
        default: null,
        nullable: true,
        env: 'MONGO_RETRY_WRITES'
      },
      readPreference: {
        doc: 'Mongo read preference, overrides mongo URI when set.',
        format: [
          'primary',
          'primaryPreferred',
          'secondary',
          'secondaryPreferred',
          'nearest'
        ],
        default: null,
        nullable: true,
        env: 'MONGO_READ_PREFERENCE'
      }
    }
  },
  httpProxy: {
    doc: 'HTTP Proxy URL',
    format: String,
    nullable: true,
    default: null,
    env: 'HTTP_PROXY'
  },
  tracing: {
    header: {
      doc: 'CDP tracing header name',
      format: String,
      default: 'x-cdp-request-id',
      env: 'TRACING_HEADER'
    }
  },
  govukNotify: {
    apiKey: {
      doc: 'GOV.UK Notify API key',
      format: String,
      default: '',
      sensitive: true,
      env: 'GOVUK_NOTIFY_API_KEY'
    },
    authenticationTemplateId: {
      doc: 'GOV.UK Notify email template ID for the sign-in passcode (uses ((code)))',
      format: String,
      default: '',
      env: 'GOVUK_NOTIFY_AUTHENTICATION_TEMPLATE_ID'
    }
  },
  otp: {
    secret: {
      doc: 'Secret used to hash passcodes before they are stored. Required in production',
      format: String,
      default: '',
      sensitive: true,
      env: 'OTP_HASH_SECRET'
    },
    ttlMinutes: {
      doc: 'Minutes a passcode stays valid',
      format: 'nat',
      default: 10,
      env: 'OTP_TTL_MINUTES'
    },
    maxAttempts: {
      doc: 'Wrong guesses allowed before the passcode is locked',
      format: 'nat',
      default: 5,
      env: 'OTP_MAX_ATTEMPTS'
    },
    resendCooldownSeconds: {
      doc: 'Minimum seconds between passcode emails to the same address',
      format: 'nat',
      default: 60,
      env: 'OTP_RESEND_COOLDOWN_SECONDS'
    }
  }
})

config.validate({ allowed: 'strict' })

if (isProduction && !config.get('otp.secret')) {
  throw new Error('OTP_HASH_SECRET must be set in production')
}
